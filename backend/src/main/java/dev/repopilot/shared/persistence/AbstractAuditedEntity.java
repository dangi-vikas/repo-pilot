package dev.repopilot.shared.persistence;

import jakarta.persistence.Column;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PostLoad;
import jakarta.persistence.PostPersist;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Transient;
import jakarta.persistence.Version;
import org.hibernate.annotations.UuidGenerator;
import org.springframework.data.domain.Persistable;

import java.time.Instant;
import java.util.Objects;
import java.util.UUID;

/**
 * Identity, audit timestamps and optimistic locking for mutable aggregates.
 *
 * <p>Optimistic locking is declared once here rather than per entity because
 * RepoPilot has several writers that can touch the same row concurrently: the job
 * dispatcher, the job worker, and the HTTP API. A lost update on an
 * {@code analysis_job} would mean a cancelled job that keeps running, so the
 * database must be able to detect it.
 *
 * <p>Immutable, append-only rows (source files, symbols, findings, edges) do not
 * extend this type: they are written once per revision and never updated, so a
 * version column would be dead weight.
 *
 * <h2>Why this implements {@link Persistable}</h2>
 *
 * <p>Spring Data decides between {@code persist} and {@code merge} from
 * {@code isNew(entity)}. Its default heuristic for a versioned entity is "is the
 * version property null?". That heuristic is wrong here for two reasons:
 *
 * <ol>
 *   <li>The identifier is generated by Hibernate at flush time, so it is also null on
 *       a brand new instance and cannot be used to tell new from detached.</li>
 *   <li>{@link #getVersion()} intentionally reports {@code 0} before the first flush
 *       rather than leaking a null to callers, so the property reads as non-null even
 *       for an unsaved entity.</li>
 * </ol>
 *
 * <p>The default therefore classifies every new instance as detached, and
 * {@code save} routes to {@code merge}. {@code merge} copies the state into a new
 * managed instance and returns <em>that</em> instance: the caller's reference is left
 * with a null id, no {@code createdAt}, and no {@code updatedAt}. Code that persists an
 * entity and then serialises the same reference — which the HTTP layer does on every
 * create — would return a resource with no identifier.
 *
 * <p>Because the version property cannot express newness honestly, this class declares
 * it explicitly through {@link Persistable#isNew()}. New instances report {@code true}
 * until they are persisted or loaded, so {@code save} always routes to {@code persist}
 * and the generated identity lands on the caller's reference.
 */
@MappedSuperclass
public abstract class AbstractAuditedEntity implements Persistable<UUID> {

    /**
     * Surrogate key, assigned by Hibernate's UUID generator at persist time.
     *
     * <p>It is deliberately <em>not</em> pre-populated in a field initialiser. Hibernate's
     * transient/detached decision for a generated identifier is "is the id null?", so a
     * pre-assigned id makes a brand new entity look detached and the insert fails.
     */
    @Id
    @UuidGenerator
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /**
     * Optimistic locking version.
     *
     * <p>Deliberately a boxed {@link Long} rather than a primitive. Hibernate's
     * unsaved-value detection for a versioned entity is "is the version null?", and a
     * primitive long is never null — so Hibernate would classify a brand new entity as
     * detached and issue an UPDATE instead of an INSERT, failing with
     * {@code StaleObjectStateException}. On insert Hibernate writes the numeric seed
     * value (0), which satisfies the column's {@code NOT NULL DEFAULT 0}.
     */
    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    /**
     * Explicit newness marker, consulted by Spring Data instead of the version
     * heuristic. {@link Transient} keeps it out of the mapping; it is flipped to
     * {@code false} as soon as the row exists or is read back.
     */
    @Transient
    private boolean newEntity = true;

    @PrePersist
    void markCreated() {
        Instant now = Instant.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    @PreUpdate
    void markUpdated() {
        this.updatedAt = Instant.now();
    }

    @PostPersist
    @PostLoad
    void markPersisted() {
        this.newEntity = false;
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    @Override
    public boolean isNew() {
        return newEntity;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    /** Current optimistic-lock version; {@code 0} before the first flush. */
    public long getVersion() {
        return version == null ? 0L : version;
    }

    /**
     * Identity is the assigned UUID, and it is assigned before persistence, so
     * equality can be based on it. Two unsaved instances are never equal.
     */
    @Override
    public final boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (!(other instanceof AbstractAuditedEntity that)) {
            return false;
        }
        return getClass() == that.getClass() && id != null && id.equals(that.id);
    }

    @Override
    public final int hashCode() {
        return Objects.hash(getClass(), id);
    }
}
